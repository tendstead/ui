import AxeBuilder from '@axe-core/playwright';
test('desktop uses registry for active nested routes, zero badges and optional services', async ({page}) => {
  await page.goto('/?route=/receipts/review/42&services=1&account=1');
  const nav=page.getByRole('navigation',{name:'Main navigation',exact:true});
  await expect(nav.getByRole('link',{name:'Review queue'})).toHaveAttribute('aria-current','page');
  await expect(nav.getByRole('link',{name:'Receipts 0'})).toBeVisible();
  await expect(page.getByRole('navigation',{name:'Connected services'}).getByRole('link',{name:'Shopping list'})).toHaveAttribute('href','https://shopping.example.test/');
  await expect(page.getByRole('button',{name:'Alex · local account'})).toBeVisible();
  await nav.getByRole('link',{name:'Search'}).click();
  await expect(page.getByRole('heading',{name:'Search',exact:true})).toBeVisible();
  expect(new URL(page.url()).pathname).toBe('/search');
});
test('mobile drawer is named, traps focus, closes and restores focus and scrolling', async ({page}) => {
  await page.setViewportSize({width:393,height:873});
  await page.goto('/?services=1&account=1');
  const menu=page.getByRole('button',{name:'Menu',exact:true});
  await menu.click();
  const drawer=page.getByRole('dialog',{name:'All destinations'});
  await expect(drawer).toBeVisible();
  expect(await page.locator('[data-shell-background]').evaluate(el=>(el as HTMLElement).inert)).toBe(true);
  await drawer.getByRole('button',{name:'Close menu'}).focus();
  await page.keyboard.press('Shift+Tab');
  expect(await drawer.evaluate(el=>el.contains(document.activeElement))).toBe(true);
  for(let i=0;i<15;i++) await page.keyboard.press('Tab');
  expect(await drawer.evaluate(el=>el.contains(document.activeElement))).toBe(true);
  await page.keyboard.press('Escape');
  await expect(drawer).toBeHidden();
  await expect(menu).toBeFocused();
  expect(await page.locator('[data-shell-background]').evaluate(el=>(el as HTMLElement).inert)).toBe(false);
  await menu.click();
  await page.locator('[data-drawer-overlay]').click({position:{x:5,y:5}});
  await expect(drawer).toBeHidden();
  await menu.click();
  await page.setViewportSize({width:1280,height:800});
  await expect(drawer).toBeHidden();
  expect(await page.locator('body').evaluate(el=>getComputedStyle(el).overflow)).not.toBe('hidden');
});
test('mobile action and complete menu support reactive permission removal', async ({page}) => {
  await page.setViewportSize({width:360,height:740});
  await page.goto('/?app=receipts&controls=1');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Add receipt',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Menu',exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('link',{name:'Settings'})).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('checkbox',{name:'Allow receipt access'}).uncheck();
  await expect(page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Receipts 0'})).toHaveCount(0);
  await page.getByRole('button',{name:'Menu',exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('link',{name:'Receipts 0'})).toHaveCount(0);
});
